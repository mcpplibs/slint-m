#!/usr/bin/env python3
"""Write the module units of mcpplibs.mwrap.slint from the SDK's headers.

  src/slint.cppm        mcpplibs.mwrap.slint: namespace slint and
                        slint::language, by `using` (upstream's names)
  src/interpreter.cppm  mcpplibs.mwrap.slint.interpreter: slint::interpreter
  src/platform.cppm     mcpplibs.mwrap.slint.platform: slint::platform and
                        slint::platform::key_codes -- Clang only (below)
  src/macros.cppm       mcpplibs.mwrap.slint.macros: every SLINT_FEATURE_* the
                        headers test, as `inline constexpr bool`

THE PLATFORM MODULE IS CLANG'S. GCC 16 reports "exposes TU-local entity"
for SoftwareRenderer::render_by_line (a lambda in its requires-clause), and,
with that class left out, crashes importing any module built over
slint-platform.h (an internal compiler error). Under GCC the unit declares the
module and nothing else; a program includes <slint-platform.h> before its
imports, which is the same API.

With --check, nothing is written and a difference fails.
"""
import argparse
from pathlib import Path
import sys

sys.path.insert(0, str(Path(__file__).resolve().parent))
from inventory import fetch, find_clang, surface  # noqa: E402

BANNER = '// Generated by tools/gen_exports.py from Slint 1.19.0\'s SDK headers -- do not\n// edit by hand.'


def using_block(ns: str, names: list[str], indent: str = '') -> list[str]:
    return [f'{indent}using {ns}::{n};' for n in names]


def core_unit(sf) -> str:
    out = [BANNER, '//',
           '// mcpplibs.mwrap.slint -- Slint\'s C++ runtime API: windows and components,',
           '// properties\' types (SharedString, SharedVector, Color, Brush, Image …), models,',
           '// timers and the event loop, and slint::language. The names are upstream\'s;',
           '// the library is compat.slint\'s libslint_cpp. A component compiled from a',
           '// `.slint` file (slint.mcpp.plugins) is used beside this module.',
           'module;', '#include <slint.h>', '', 'export module mcpplibs.mwrap.slint;', '',
           'export import mcpplibs.mwrap.slint.macros;', '', 'export namespace slint {']
    out += using_block('slint', sf.names['slint'])
    out += ['', 'namespace language {']
    out += using_block('slint::language', sf.names['slint::language'])
    out += ['}  // namespace language', '}  // namespace slint']
    return '\n'.join(out) + '\n'


def interpreter_unit(sf) -> str:
    out = [BANNER, '//',
           '// mcpplibs.mwrap.slint.interpreter -- loading `.slint` files at run time',
           '// (ComponentCompiler, ComponentDefinition, ComponentInstance, Value …); needs',
           '// the SDK\'s `interpreter` feature (SLINT_FEATURE_INTERPRETER).',
           'module;', '#include <slint.h>', '#include <slint-interpreter.h>', '',
           'export module mcpplibs.mwrap.slint.interpreter;', '', 'export import mcpplibs.mwrap.slint;', '',
           'export namespace slint::interpreter {']
    out += using_block('slint::interpreter', sf.names['slint::interpreter'])
    out += ['}  // namespace slint::interpreter']
    return '\n'.join(out) + '\n'


def platform_unit(sf) -> str:
    keys = sf.names['slint::platform::key_codes']
    out = [BANNER, '//',
           '// mcpplibs.mwrap.slint.platform -- the platform API: a Platform that creates',
           '// window adapters, the software renderer, timers. Clang only (see',
           '// tools/gen_exports.py): under GCC 16 the module is empty and a program',
           '// includes <slint-platform.h> before its imports.',
           '//',
           '// slint::platform::key_codes are `constexpr char32_t` constants, which have',
           '// internal linkage and cannot be exported: each is captured here and',
           '// defined, of its type and value, under its name in',
           '// mcpplibs::mwrap::slint::platform::key_codes.',
           'module;', '#if defined(__clang__)', '#include <slint.h>', '#include <slint-platform.h>', '',
           'namespace mwrap_slint_keys {']
    out += [f'inline constexpr auto value_{k} = slint::platform::key_codes::{k};' for k in keys]
    out += ['}  // namespace mwrap_slint_keys', '#endif', '',
            'export module mcpplibs.mwrap.slint.platform;', '', 'export import mcpplibs.mwrap.slint;', '',
            '#if defined(__clang__)', 'export namespace slint::platform {']
    out += using_block('slint::platform', sf.names['slint::platform'])
    out += ['}  // namespace slint::platform', '',
            'export namespace mcpplibs::mwrap::slint::platform::key_codes {']
    out += [f'inline constexpr auto {k} = mwrap_slint_keys::value_{k};' for k in keys]
    out += ['}  // namespace mcpplibs::mwrap::slint::platform::key_codes', '#endif']
    return '\n'.join(out) + '\n'


def macros_unit(sf) -> str:
    out = [BANNER, '//',
           '// mcpplibs.mwrap.slint.macros -- the SDK\'s features as `inline constexpr bool`',
           '// in mcpplibs::mwrap::slint::macros, each true exactly when its SLINT_FEATURE_*',
           '// macro is defined by the headers compat.slint provides; for `if constexpr`.',
           '// <mwrap/slint/macros.hpp> (= <slint.h>) keeps the macros for #if.',
           'module;', '#include <slint.h>', '', 'namespace mwrap_slint_features {']
    for f in sf.feature_universe:
        out += [f'#ifdef {f}', f'inline constexpr bool value_{f} = true;', '#else',
                f'inline constexpr bool value_{f} = false;', '#endif']
    out.append('}  // namespace mwrap_slint_features')
    out += [f'#undef {f}' for f in sf.feature_universe]
    out += ['', 'export module mcpplibs.mwrap.slint.macros;', '',
            'export namespace mcpplibs::mwrap::slint::macros {']
    out += [f'inline constexpr bool {f} = mwrap_slint_features::value_{f};' for f in sf.feature_universe]
    out.append('}  // namespace mcpplibs::mwrap::slint::macros')
    return '\n'.join(out) + '\n'


def render(sf) -> dict[str, str]:
    return {'src/slint.cppm': core_unit(sf), 'src/interpreter.cppm': interpreter_unit(sf),
            'src/platform.cppm': platform_unit(sf), 'src/macros.cppm': macros_unit(sf)}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--clang')
    parser.add_argument('--sdk')
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[1]
    files = render(surface(fetch(root, args.sdk), find_clang(args.clang)))
    stale = []
    for relative, text in files.items():
        path = root / relative
        if path.exists() and path.read_text(encoding='utf-8') == text:
            continue
        if args.check:
            stale.append(relative)
        else:
            path.write_text(text, encoding='utf-8', newline='\n')
            print('wrote', relative)
    extra = sorted(p.relative_to(root).as_posix() for p in (root / 'src').glob('*.cppm')
                   if p.relative_to(root).as_posix() not in files)
    stale += [f'{e} (not generated)' for e in extra]
    if stale:
        sys.exit('not what tools/gen_exports.py writes: ' + ', '.join(stale))


if __name__ == '__main__':
    main()
